import numpy as np
import streamlit as st

from lib import figs, sim, ui

ui.hero("الدرس 6", "فكرة التشبع: متغيرات أكثر من المشاهدات", "Saturation and the split-half algorithm",
        "كيف نقدّر نموذجًا فيه مؤشر لكل مشاهدة، أي معالم أكثر من البيانات؟ الجواب حيلة بسيطة وأنيقة: "
        "نقسم المؤشرات إلى كتل ونفحص كل كتلة على حدة. في هذا الدرس ستشاهد الخوارزمية تعمل خطوة بخطوة.", "teal")
ui.objectives([
    "خطوات خوارزمية النصفين بالترتيب",
    "لماذا تعمل: العلاقة بين النبضة وحذف المشاهدة",
    "النتيجة النظرية الأساسية: عدد المؤشرات الزائفة المتوقع",
    "كيف تطورت الخوارزمية في البرمجيات الحديثة",
], minutes=20)

st.markdown("## 🧩 المشكلة")
st.markdown(
    """
في الدرس السابق رأينا أن وضع مؤشر لكل تاريخ يعطي نموذجًا فيه $k + T$ معلمة و$T$ مشاهدة فقط. المربعات الصغرى تحتاج
مشاهدات **أكثر** من المعالم. فهل نستسلم؟ لا: لا نحتاج أن نضع **كل** المؤشرات **في وقت واحد**.
"""
)

st.markdown("## ✂️ الحل: خوارزمية النصفين")
st.markdown(f"اقترحها Hendry وحلّلها رياضيًا Hendry وJohansen وSantos (2008). خطواتها لـ IIS:")
ui.steps([
    ("الكتلة الأولى", "أضف نبضات النصف الأول فقط (T/2 مؤشرًا) وقدّر النموذج: هذا ممكن لأن المعالم الآن أقل من المشاهدات. "
     "احتفظ بالمؤشرات التي |t| لها أكبر من القيمة الحرجة."),
    ("الكتلة الثانية", "أزل نبضات النصف الأول، وأضف نبضات النصف الثاني، وكرر الشيء نفسه."),
    ("الاتحاد", "اجمع كل المؤشرات التي نجحت في الكتلتين في نموذج واحد، وأعد اختبارها، واحذف ما لم يعد معنويًا."),
    ("النموذج النهائي", "ما يبقى هو قائمة القيم الشاذة: تواريخها وأحجامها، مع تقدير نظيف لبقية المعاملات."),
], "teal")

with ui.box("why", "لماذا تعمل الحيلة؟"):
    st.markdown(
        """
هنا السر: **إضافة نبضة لمشاهدة ما تعادل حذف تلك المشاهدة من التقدير**. المعامل يلتقط قيمتها كاملة فلا تؤثر في
بقية المعاملات. فحين نضيف نبضات النصف الأول، نكون في الحقيقة **نقدّر النموذج من النصف الثاني وحده**، ثم نسأل عن كل
مشاهدة من النصف الأول: «هل تتوافق مع هذا النموذج؟». المشاهدة الشاذة لا تتوافق، فيظهر معاملها كبيرًا.
وبما أن النموذج قُدّر من النصف الآخر، فالشذوذ **لا يستطيع أن يلوث** النموذج الذي يُختبر به، فتنتهي مشكلة الإخفاء.
"""
    )
with ui.box("analogy", "تصحيح الامتحانات بالتبادل"):
    st.markdown("معلم يريد كشف الغش في فصل من 40 طالبًا. يقسمهم إلى مجموعتين: يحسب «المستوى الطبيعي» من إجابات المجموعة "
                "الثانية، ثم يقارن به كل طالب من الأولى. الطالب الذي تختلف إجاباته اختلافًا كبيرًا يُعلَّم. ثم يبدل المجموعتين. "
                "الغشاش لا يستطيع أن يرفع «المستوى الطبيعي» لأنه لم يُستخدم في حسابه.")

st.markdown("## ▶️ شاهد الخوارزمية خطوة بخطوة")
st.markdown(
    """
صمّم بياناتك بأشرطة التمرير ثم اضغط ▶:
- **الرسم الأعلى**: البيانات والقيمة المقدَّرة في كل مرحلة؛ الكتلة الحالية مظللة.
- **الرسم الأسفل**: قيمة |t| لكل مؤشر مرشح؛ الملون محتفظ به، والرمادي مستبعد، والخط الأحمر هو القيمة الحرجة.
"""
)
with st.container(border=True):
    a, b, c, d = st.columns(4)
    T = a.slider("عدد المشاهدات T", 40, 150, 80, 10, key="sat_T")
    o_size = b.slider("حجم القيمة الشاذة", 0.0, 10.0, 6.0, 0.5, key="sat_o")
    s_size = c.slider("حجم تحول المستوى", 0.0, 6.0, 3.0, 0.5, key="sat_s")
    alpha = d.select_slider("مستوى الدلالة المستهدف α", [0.001, 0.005, 0.01, 0.025, 0.05], 0.01, key="sat_a")
    kinds = st.pills("أنواع المؤشرات", ["IIS", "SIS"], selection_mode="multi", default=["IIS"], key="sat_k")
    seed = st.number_input("البذرة العشوائية (غيّرها لترى بيانات أخرى)", 1, 999, 3, key="sat_seed")

kinds = kinds or ["IIS"]
t, y, x, mu = sim.dgp(T, seed=int(seed), outliers=[(int(T * 0.3), o_size)] if o_size else None,
                      shifts=[(int(T * 0.65), s_size)] if s_size else None)
sets = [(k, *sim.build_set(k, T)) for k in kinds]
res = figs.run_search(y, np.ones((T, 1)), sets, alpha)
st.plotly_chart(figs.search_animation(t, y, res, mu), key=f"satanim_{T}_{o_size}_{s_size}_{alpha}_{kinds}_{seed}")

kinds_found = res.__dict__["_all_kinds"]
found = "، ".join(f"{kinds_found[j]} عند t={tau}" for j, tau in zip(res.selected, res.taus)) or "لا شيء"
with ui.box("example", "ماذا وجدت الخوارزمية؟"):
    st.markdown(f"**المؤشرات المحتفظ بها:** {found}.\n\n"
                f"**الحقيقة التي صممتها:** قيمة شاذة عند t={int(T * 0.3)}، وتحول مستوى عند t={int(T * 0.65)}.")
if kinds == ["IIS"] and s_size >= 2:
    with ui.box("think", "لاحظ"):
        st.markdown("مع IIS وحده يُلتقط تحول المستوى بسلسلة من النبضات، إن التُقط أصلًا. أضف SIS من الأزرار أعلاه "
                    "وشاهد كيف يُلتقط التحول بمؤشر واحد.")

st.markdown("## 📐 النتيجة النظرية الأساسية")
st.markdown("ماذا لو لم تكن في البيانات أي قيمة شاذة؟ كل نبضة تُختبر بمستوى α، فيكون:")
with ui.box("formula", "العدد المتوقع للمؤشرات الزائفة"):
    st.latex(r"E[\text{عدد المؤشرات الزائفة}] = \alpha \times T")
    st.markdown("مثال: مع $T=100$ و$\\alpha=0.01$ نتوقع **مؤشرًا زائفًا واحدًا** في المتوسط. هذا ثمن زهيد مقابل الحماية "
                "من **كل** القيم الشاذة الممكنة في مئة تاريخ. وهو أساس مفهوم المقياس (gauge) الذي سنراه بعد درسين.")
with ui.box("warn", "خطأ شائع"):
    st.markdown("يستخدم كثير من المبتدئين α = 0.05 كما في الاختبارات العادية. مع 200 مشاهدة يعني ذلك **10 مؤشرات زائفة** "
                "في المتوسط، يحاول الباحث بعدها تفسيرها بأحداث تاريخية لا علاقة لها بها! استخدم α قريبًا من 1/T.")

with st.expander("📦 من النصفين إلى عدة كتل: كيف تعمل البرمجيات الحديثة؟"):
    st.markdown(
        """
- **gets/isat وindsat:** لا نكتفي بنصفين؛ يُحدَّد عدد الكتل من نسبة (ratio threshold) وحد أقصى لحجم الكتلة (عادة 30)،
  وداخل كل كتلة يُجرى **بحث متعدد المسارات** (GETS، الدرس التالي)، ثم بحث أخير على الاتحاد.
- **Autometrics:** بحث شجري يضيف ويحذف كتلًا مع اختبارات تشخيصية.
- **الخلاصة:** الكتل الأكثر والبحث متعدد المسارات يزيدان القوة، لكن المبدأ هو نفسه مبدأ النصفين.
"""
        )

ui.check("لماذا لا تستطيع القيمة الشاذة في النصف الأول أن «تخفي نفسها» في خوارزمية النصفين؟",
         ["لأن α صغير", "لأن النموذج الذي تُختبر به قُدِّر من النصف الثاني فقط", "لأنها تُحذف قبل التقدير",
          "لأن OLS لا يتأثر بالشذوذ"], 1, "إضافة نبضات النصف الأول تعادل تقدير النموذج من النصف الآخر.", "sat_q1")
ui.check("مع T = 300 وα = 0.01 كم مؤشرًا زائفًا نتوقع إذا لم يوجد أي شذوذ؟", ["0.3", "3", "30", "1"], 1,
         "α × T = 0.01 × 300 = 3.", "sat_q2")
ui.summary([
    "لا نضع كل المؤشرات معًا: نقسمها إلى كتل ونفحص كل كتلة على حدة ثم نجمع الناجح منها.",
    "إضافة نبضة تعادل حذف المشاهدة؛ فكل كتلة تُختبر بنموذج من بقية البيانات، فلا يقع الإخفاء.",
    "دون شذوذ نحتفظ في المتوسط بـ α × T مؤشرًا زائفًا: اختر α قريبًا من 1/T.",
    "البرمجيات الحديثة تستخدم كتلًا أكثر وبحثًا متعدد المسارات، والمبدأ واحد.",
])
ui.nav_hint("البحث من العام إلى الخاص")
