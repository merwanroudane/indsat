import streamlit as st

from lib import ui

ui.header("اختبر نفسك", "Self-assessment quiz", "عشرة أسئلة تغطي المحاضرة؛ تحصل على التصحيح والشرح فورًا", "orange")

Q = [
    ("من صاحب فكرة تشبع المؤشرات وفي أي سنة؟",
     ["Bai و Perron، 1998", "Hendry، 1999", "Chow، 1960", "Johansen، 1988"], 1,
     "اقترحها David Hendry سنة 1999 في دراسة الإنفاق على الغذاء في الولايات المتحدة."),
    ("مع T = 200 و α = 0.005، ما العدد المتوقع للنبضات الزائفة تحت الفرضية العدمية؟",
     ["0.5", "1", "2", "10"], 1, "αT = 0.005 × 200 = 1."),
    ("أي نوع هو الأنسب لتحول دائم في متوسط السلسلة؟", ["IIS", "SIS", "DIS", "PIS"], 1,
     "الدرجة (SIS) تساوي 1 من تاريخ الكسر فصاعدًا، فتلتقط تحول المستوى بمؤشر واحد."),
    ("ماذا يكشف MIS؟", ["القيم الشاذة", "تحولات المستوى", "تغيّر معامل متغير", "أخطاء التوقيت"], 2,
     "MIS يضرب الدرجات في المتغير x فيلتقط تغيّر ميله عبر الزمن."),
    ("لماذا يمكن تقدير نموذج فيه مؤشرات أكثر من المشاهدات؟",
     ["لأننا نستخدم OLS العادية", "لأننا نقسم المؤشرات إلى كتل قابلة للتقدير", "لأننا نحذف المشاهدات", "لا يمكن"], 1,
     "خوارزمية النصفين (أو الكتل) تضيف جزءًا من المؤشرات في كل مرة ثم تجمع الناجيات."),
    ("ما معنى الـ gauge؟", ["نسبة المؤشرات الحقيقية المكتشفة", "نسبة المؤشرات الزائفة المحتفظ بها",
                             "القيمة الحرجة", "عدد الكتل"], 1, "الـ gauge يقابل الحجم: نريده قريبًا من α."),
    ("كم تقريبًا كفاءة IIS (α = 1%) مقارنة بـ OLS حين لا توجد قيم شاذة؟", ["50%", "75%", "93%", "100%"], 2,
     "حسب Johansen & Nielsen: الكفاءة نحو 93%، فالتأمين رخيص."),
    ("سلسلة نبضات متتالية بنفس الإشارة تشير غالبًا إلى:", ["قيم شاذة مستقلة", "تحول مستوى",
                                                             "خطأ في البرنامج", "ارتباط ذاتي إيجابي"], 1,
     "الدرجة مجموع نبضات متتالية؛ استخدم SIS أو super."),
    ("ما ترتيب super saturation؟", ["IIS + TIS", "IIS + SIS", "SIS + MIS", "IIS + SIS + TIS"], 1,
     "super = IIS + SIS؛ أما ultra فيضيف TIS."),
    ("أي نوع يناسب صدمة بركانية: هبوط حاد ثم تعافٍ تدريجي؟", ["SIS", "TIS", "BIS", "PIS"], 2,
     "الكسور المصمَّمة (BIS) تستخدم شكل الاستجابة المعروف (Pretis et al. 2016)."),
]

score = 0
answered = 0
for i, (q, opts, ans, expl) in enumerate(Q, 1):
    with st.container(border=True):
        st.markdown(f"**السؤال {i}.** {q}")
        choice = st.radio("الخيارات", opts, index=None, key=f"q{i}", label_visibility="collapsed")
        if choice is not None:
            answered += 1
            if opts.index(choice) == ans:
                score += 1
                st.success(f"صحيح. {expl}", icon=":material/check_circle:")
            else:
                st.error(f"الإجابة الصحيحة: {opts[ans]}. {expl}", icon=":material/cancel:")

st.divider()
c1, c2 = st.columns(2)
c1.metric("أجبت عن", f"{answered} / {len(Q)}")
c2.metric("النتيجة", f"{score} / {len(Q)}")
if answered == len(Q):
    if score >= 8:
        st.balloons()
        ui.good("ممتاز! أنت جاهز للانتقال إلى التطبيق على بياناتك.")
    else:
        ui.warn("راجع الدروس المرتبطة بالأسئلة التي أخطأت فيها ثم أعد المحاولة.")
ui.nav_hint("المراجع")
