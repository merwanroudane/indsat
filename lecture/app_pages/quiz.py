score = 0
answered = 0
for i, (q, opts, ans, expl) in enumerate(Q, 1):
    with ui.box("think", f"السؤال {i}"):
        st.markdown(f"**{q}**")
        choice = st.radio("الخيارات", opts, index=None, key=f"q{i}", label_visibility="collapsed")
        if choice is not None:
            answered += 1
            if opts.index(choice) == ans:
                score += 1
                st.success(f"صحيح. {expl}", icon=":material/check_circle:")
            else:
                st.error(f"الإجابة الصحيحة: {opts[ans]}. {expl}", icon=":material/cancel:")

st.divider()
c1, c2 = st.columns(2)
c1.metric("أجبت عن", f"{answered} / {len(Q)}")
c2.metric("النتيجة", f"{score} / {len(Q)}")
if answered == len(Q):
    if score >= 12:
        st.balloons()
        ui.good("ممتاز! أنت جاهز للانتقال إلى التطبيق على بياناتك.")
    else:
        ui.warn("راجع الدروس المرتبطة بالأسئلة التي أخطأت فيها ثم أعد المحاولة.")
