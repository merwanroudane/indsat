import streamlit as st

from lib import figs, ui

ui.header("البحث من العام إلى الخاص", "General-to-specific (GETS) model selection",
          "المحرك الذي يختار المؤشرات داخل كل كتلة", "green")

st.markdown(
    f"""
{ui.t('منهج العام إلى الخاص', 'General-to-Specific, GETS')} مدرسة لندن للاقتصاد ثم أكسفورد (Hendry):
ابدأ بنموذج **عام** يضم كل ما قد يكون مهمًا — {ui.t('النموذج العام غير المقيَّد', 'GUM: General Unrestricted Model')} —
ثم احذف تدريجيًا ما ليس معنويًا، مع التأكد أن النموذج المختصر ما زال سليمًا إحصائيًا.
"""
)
st.markdown("## :material/play_circle: الحذف التراجعي خطوة بخطوة")
st.markdown("نموذج فيه 10 متغيرات، ثلاثة منها فقط (x1، x4، x7) مؤثرة فعلًا. في كل إطار يُحذف المتغير ذو أصغر |t| "
            "إذا كان دون القيمة الحرجة. **الأزرق:** معنوي، **الأصفر:** غير معنوي، **الرمادي:** حُذف. اضغط ▶.")
c1, c2 = st.columns([1, 3])
seed = c1.number_input("البذرة", 1, 99, 4, key="gets_seed")
alpha = c1.select_slider("α", [0.01, 0.05, 0.10], 0.05, key="gets_a")
c2.plotly_chart(figs.gets_animation(seed=int(seed), alpha=alpha), key=f"gets_{seed}_{alpha}")

st.markdown("## :material/account_tree: لماذا مسارات متعددة؟")
st.markdown(
    """
الحذف بمسار واحد قد يضل الطريق: حذف متغير مبكرًا قد يجعل متغيرًا آخر مهمًا يبدو غير معنوي (بسبب الارتباط بينهما).
لذلك تبدأ الخوارزميات الحديثة **مسارًا منفصلًا من كل متغير غير معنوي** في النموذج العام:

| الخطوة | ماذا يحدث |
|---|---|
| 1 | قدّر النموذج العام (GUM) وحدد المتغيرات غير المعنوية |
| 2 | لكل متغير غير معنوي: ابدأ مسارًا يحذفه أولًا، ثم احذف الأضعف فالأضعف |
| 3 | كل مسار ينتهي بـ **نموذج طرفي** (terminal model) كل متغيراته معنوية |
| 4 | اختر بين النماذج الطرفية بمعيار معلومات (SC أو AIC أو HQ) |
| 5 | (اختياري) تحقق في كل خطوة أن الاختبارات التشخيصية لم تُرفض |

هذا ما يفعله Hoover & Perez (1999) وPcGets وAutometrics وgets::getsFun ومكتبة indsat.
"""
)
ui.key_idea("في التشبع، المتغيرات «المرشحة للحذف» هي المؤشرات فقط، أما متغيرات النموذج الاقتصادي (x) "
            "فتبقى ثابتة في كل الخطوات. فالتشبع = GETS على المؤشرات مع الحفاظ على نظرية الباحث.")

st.markdown("## :material/rule: مستوى الدلالة المستهدف")
st.markdown(
    r"""
القيمة الحرجة $c_\alpha$ تأتي من مستوى الدلالة المستهدف $\alpha$ (target size). مع اختبار ثنائي الطرف:

| α | 0.05 | 0.01 | 0.005 | 0.001 |
|---|---|---|---|---|
| $c_\alpha$ | 1.96 | 2.58 | 2.81 | 3.29 |

قاعدة عملية شائعة: $\alpha \approx 1/T$ حتى يبقى عدد المؤشرات الزائفة المتوقع قريبًا من واحد.
"""
)
ui.nav_hint("المقياس والقوة")
