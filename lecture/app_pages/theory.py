import streamlit as st

from lib import figs, sim, ui

ui.hero("الدرس 9 (اختياري)", "النظرية الإحصائية", "Asymptotic theory — IIS as a robust Huber-skip estimator",
        "هذا الدرس لمن يريد أن يعرف لماذا يمكن الوثوق بالمنهجية رياضيًا. يمكن للمبتدئ أن يقرأ الشرح بالكلمات ويتجاوز الصيغ، "
        "فالفكرة الأساسية بسيطة: التشبع تأمين رخيص جدًا ضد القيم الشاذة.", "pink")
ui.objectives([
    "معنى «المقدِّر القوي» ولماذا IIS واحد منها",
    "عامل الاتساق ξ: لماذا نصحح تقدير التباين",
    "الكفاءة: كم «ندفع» ثمنًا حين لا توجد قيم شاذة",
    "النتائج النظرية التي تقوم عليها الاختبارات اللاحقة",
], minutes=20)

st.markdown("## 🛡️ ما المقدِّر القوي؟")
st.markdown(
    f"""
المربعات الصغرى ممتازة **إذا** كانت البيانات نظيفة، لكنها تنهار أمام قيمة شاذة واحدة كبيرة كما رأيت. أما
{ui.t('المقدِّر القوي', 'robust estimator')} فهو مقدِّر لا يتأثر كثيرًا بنسبة صغيرة من المشاهدات الملوثة. الإحصائيون
طوروا عائلات كثيرة منها منذ الستينيات، أشهرها مقدِّرات **Huber**.

الاكتشاف الجميل لـ Johansen وNielsen (2009) أن IIS، الذي ولد من فكرة عملية في الاقتصاد القياسي، هو في الحقيقة
**عضو في هذه العائلة المعروفة**: إنه {ui.t('مقدِّر Huber-skip', 'Huber-skip M-estimator')}. وهذا يعني أن كل النظرية
الإحصائية المعروفة عن هذه المقدِّرات تنطبق عليه.
"""
)
with ui.box("analogy", "حكَم يستبعد الدرجات المتطرفة"):
    st.markdown("في مسابقات الغطس يمنح سبعة حكام درجات، ثم **تُستبعد** أعلى درجة وأدنى درجة ويُحسب المتوسط من الباقي. "
                "هكذا لا يستطيع حكم واحد متحيز أن يغير النتيجة. Huber-skip يفعل الشيء نفسه مع المشاهدات: "
                "يستبعد ما يتجاوز حدًا معينًا ويقدّر من الباقي.")

st.markdown("## 🔁 من الخوارزمية إلى المقدِّر")
st.markdown("خطوات Huber-skip بالكلمات: (1) قدّر النموذج مبدئيًا، (2) احسب الباقي المعياري لكل مشاهدة، "
            "(3) **تخطَّ** المشاهدات التي يتجاوز باقيها الحد c، (4) أعد التقدير بالمربعات الصغرى على الباقي. رياضيًا:")
with ui.box("formula", "مقدِّر Huber-skip ذو الخطوة الواحدة"):
    st.latex(r"\tilde\beta=\Big(\sum_{t} x_t x_t'\,\mathbf 1(|v_t|\le c)\Big)^{-1}\sum_t x_t y_t\,\mathbf 1(|v_t|\le c),"
             r"\qquad v_t=\frac{y_t-\hat\beta' x_t}{\hat\sigma}")
    st.markdown("الدالة $\\mathbf 1(|v_t|\\le c)$ تساوي 1 للمشاهدة «العادية» و0 للمشاهدة التي تُتخطى. "
                "وتكرار الخطوة m مرة يعطي **Huber-skip ذا m خطوة** (Johansen & Nielsen 2013، 2016). "
                "في indsat الخيار `algorithm(mstep) msteps(m)`.")

st.markdown("## 🔧 الكميات الأساسية")
st.markdown(
    """
حين نستبعد المشاهدات المتطرفة، يحدث أمران يجب تصحيحهما:
- **التباين المقدَّر يصغر**: حتى لو لم تكن هناك قيم شاذة، فإن الاستبعاد يزيل أطراف التوزيع الطبيعي، فيبدو الخطأ أصغر مما هو.
  لذلك نضرب التباين في **عامل الاتساق** $\\xi^2$.
- **الدقة تنخفض قليلًا**: استبعاد مشاهدات سليمة يقلل المعلومات، فيتضخم الخطأ المعياري بالعامل $\\eta$.
"""
)
with ui.box("formula", "الصيغ (تحت التوزيع الطبيعي)"):
    st.latex(r"\psi=\Phi(c)-\Phi(-c)=1-\alpha,\qquad \tau=\psi-2c\,\varphi(c),\qquad "
             r"\xi^2=\frac{\psi}{\tau},\qquad \eta_1^2=\Big(\frac{1}{\psi^2}+\frac{2\rho}{\psi}\Big)\tau+\rho^2,\ \ \rho=\frac{2c\varphi(c)}{\psi}")
    st.markdown("$\\psi$ نسبة المشاهدات التي تبقى، و$\\Phi$ و$\\varphi$ دالتا التوزيع والكثافة الطبيعيتين. الكفاءة = $1/\\eta^2$.")

st.markdown("## 🎛️ احسبها بنفسك")
a = st.select_slider("اختر α", [0.001, 0.005, 0.01, 0.025, 0.05, 0.1], 0.01, key="th_a")
f = sim.jn_factors(a)
c1, c2, c3, c4 = st.columns(4)
c1.metric("القيمة الحرجة c", f"{f['c']:.3f}")
c2.metric("ξ (اتساق σ)", f"{f['xi']:.4f}")
c3.metric("η (تضخم الخطأ المعياري)", f"{f['eta']:.4f}")
c4.metric("الكفاءة 1/η²", f"{100 * f['eff']:.1f}%")
st.plotly_chart(figs.efficiency_curve())
with ui.box("why", "تأمين رخيص"):
    st.markdown(f"مع α = {a} تبلغ كفاءة IIS نحو **{100 * f['eff']:.0f}%** من كفاءة OLS **حين لا توجد قيم شاذة أصلًا**. "
                "أي أنك تدفع قسطًا صغيرًا جدًا. وحين توجد قيم شاذة، يتفوق IIS على OLS بفارق هائل. "
                "كأنك تدفع 5% من راتبك تأمينًا يحميك من خسارة البيت كله.")

st.markdown("## 📚 نتائج نظرية أخرى تقوم عليها الأدوات")
r1, r2 = st.columns(2)
with r1:
    with ui.box("def", "توزيع المقياس: طبيعي وPoisson"):
        st.markdown("عدد المؤشرات الزائفة ≈ Poisson(αT) حين يكون α صغيرًا، ونسبتها ≈ طبيعية حين يكون α ثابتًا "
                    "(Johansen & Nielsen 2016).")
        st.latex(r"\sqrt{T}(\hat g-\alpha)\ \xrightarrow{d}\ N\big(0,\ \psi(1-\psi)+\eta_\gamma\big)")
    with ui.box("def", "اختبار نسبة القيم الشاذة"):
        st.markdown("يستخدم التوزيع أعلاه لاختبار الفرضية: لا توجد قيم شاذة (Jiao & Pretis 2022). سنطبقه في درس الاختبارات.")
        st.latex(r"z=\frac{\hat g-\alpha}{\widehat{sd}(\hat g)}\sim N(0,1)")
with r2:
    with ui.box("def", "SIS: الفروق للأمام"):
        st.markdown("تحليل Nielsen & Qian (2025) لـ SIS يعمل على الفروق. تباين المقياس أكبر منه في IIS ويتأثر بالارتباط "
                    "الذاتي، لذا يُفضَّل α أصغر.")
        st.latex(r"\chi_i=\frac{\varepsilon_i-\varepsilon_{i+1}}{\sqrt2\,\sigma}")
    with ui.box("def", "صلاحية واسعة"):
        st.markdown("النتائج تشمل الانحدار الثابت، والانحدار الذاتي، والاتجاهات الحتمية، وحتى جذر الوحدة "
                    "(بتوزيعات حدية مختلفة). أي أن المنهجية صالحة لمعظم النماذج التي يستخدمها الباحث.")

ui.check("ما معنى عامل الاتساق ξ؟",
         ["يصحح القيمة الحرجة", "يصحح تقدير التباين الذي يصغر بسبب استبعاد الأطراف", "يقيس عدد القيم الشاذة",
          "يحدد عدد الكتل"], 1, "الاستبعاد يزيل أطراف التوزيع حتى دون شذوذ، فنضخّم التباين بـ ξ².", "th_q1")
ui.summary([
    "IIS مقدِّر قوي من عائلة Huber-skip: يستبعد المتطرف ويقدّر من الباقي.",
    "نصحح التباين بعامل الاتساق ξ لأن الاستبعاد يصغّره.",
    "الكفاءة عالية جدًا دون شذوذ (نحو 93% مع α = 1%): تأمين رخيص.",
    "توزيعات المقياس (Poisson وطبيعي) هي أساس اختبارات القيم الشاذة اللاحقة.",
])
