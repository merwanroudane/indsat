    "اخترت α بناء على حجم العينة (قريبًا من 1/T)",
    "قارنت النتائج قبل التشبع وبعده في جدول واحد",
    "جربت أكثر من مستوى دلالة للتأكد من المتانة",
    "أجريت اختبار القيم الشاذة واختبار التشويه",
