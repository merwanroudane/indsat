from lib import figs, sim, ui

ui.hero("ما بعد التقدير 4", "التشبع داخل الانحدار ونماذج ARDL", "Saturating regressions and ARDL models",
        "هذا هو الاستخدام الذي يهم أغلب الباحثين: لديك انحدار أو نموذج ARDL جاهز، وتريد أن تعرف هل تشوّهه أحداث لم تنمذجها. "
        "قدّر نموذجك كالمعتاد، ثم شبّعه بأمر واحد، وقارن.", "green")
ui.objectives([
    "لماذا التشبع يحمي نموذجك ولا يستبدله",
    "سير العمل خطوة بخطوة بعد regress وARDL",
    "أثر الأحداث غير المنمذجة على المعاملات (عرض تفاعلي)",
    "التشبع في ARDL: سرعة التعديل والعلاقة طويلة الأجل واختبار الحدود",
], minutes=18)

st.markdown("## 🛡️ التشبع يحمي نموذجك")
st.markdown(
    f"""
التشبع **لا يستبدل** نموذجك الاقتصادي ولا يختار متغيراتك. متغيرات النموذج (x، والمتأخرات، والثابت) تبقى **ثابتة** أثناء البحث،
والمؤشرات وحدها هي التي تُختار. النتيجة: {ui.t('تقديرات قوية', 'robust estimates')} لمعاملاتك، مع خريطة للأحداث التي كانت
تشوهها. أنت تقرر النظرية، والخوارزمية تنظف الطريق.
"""
)
with ui.box("analogy", "تنظيف عدسة الكاميرا"):
    st.markdown("المشهد الذي تصوره (نموذجك الاقتصادي) لا يتغير، لكن بقع الغبار على العدسة (القيم الشاذة والكسور) تشوّه الصورة. "
                "التشبع ينظف العدسة دون أن يحرك الكاميرا.")
st.markdown("## 🧭 سير العمل الموصى به")
ui.steps([
    ("قدّر نموذجك المعتاد", "انحدار عادي، Newey-West، أو ARDL، كما كنت ستفعل دون تشبع."),
    ("شبّعه بالنوع المناسب", "بعد التقدير مباشرة اكتب: indsat, super tpval(0.01). أضف mis() إن شككت في معامل بعينه."),
    ("قارن", "indsat يعرض تلقائيًا جدول المقارنة ورسم المعاملات قبل التشبع وبعده."),
    ("في ARDL أعد اختبار الحدود", "المؤشرات تدخل كمتغيرات حتمية غير مقيدة، ويعاد حساب اختبار PSS."),
    ("افحص وأبلغ", "التشخيصات والرسوم، ثم قدّم النتائج **مع التشبع ودونه** في جدول واحد."),
], "green")

st.markdown("## ⚖️ عرض: الانحدار قبل التشبع وبعده")
st.markdown("البيانات الحقيقية: y = 2 + 0.8x مع تحول مستوى وقيمة شاذة لم يعرف بهما النموذج. حرّك الأشرطة وراقب كيف يبتعد "
            "معامل OLS عن الحقيقة (0.8) بينما يبقى المعامل المشبَّع قريبًا منها:")
a, b, c = st.columns(3)
shift = a.slider("تحول المستوى غير المنمذج", 0.0, 5.0, 3.0, 0.25, key="rg_s")
outl = b.slider("قيمة شاذة", 0.0, 10.0, 6.0, 0.5, key="rg_o")
seed = c.number_input("البذرة", 1, 99, 9, key="rg_seed")
T = 100
rng = np.random.default_rng(int(seed))
x = np.cumsum(rng.normal(size=T)) * 0.3 + rng.normal(size=T)
tt = np.arange(T)
y = 2 + 0.8 * x + shift * (tt >= 60) + rng.normal(size=T)
y[25] += outl
X = np.column_stack([np.ones(T), x])
f0 = sim.ols(y, X)
res = figs.run_search(y, X, [("IIS", *sim.impulses(T)), ("SIS", *sim.steps(T))], 0.01)
f1 = res.fit
rows = [("الثابت", 2.0, f0.b[0], f0.se[0], f1.b[0], f1.se[0]), ("معامل x", 0.8, f0.b[1], f0.se[1], f1.b[1], f1.se[1])]
fig = go.Figure()
for i, (nm, tru, b0, s0, b1, s1) in enumerate(rows[1:]):
    fig.add_trace(go.Scatter(x=[b0], y=["OLS"], error_x=dict(array=[1.96 * s0]), mode="markers",
                             marker=dict(size=14, color="#868e96"), name="OLS العادي"))
    fig.add_trace(go.Scatter(x=[b1], y=["المشبَّع"], error_x=dict(array=[1.96 * s1]), mode="markers",
                             marker=dict(size=14, color="#d6336c", symbol="diamond"), name="بعد التشبع"))
    fig.add_vline(x=tru, line_dash="dash", line_color="#2f9e44", annotation_text="الحقيقة 0.8")
st.plotly_chart(figs._base_layout(fig, "معامل x مع مجال ثقة 95%: قبل التشبع وبعده", 300))
k1, k2, k3 = st.columns(3)
k1.metric("معامل x (OLS)", f"{f0.b[1]:.3f}", delta=f"{f0.b[1] - 0.8:+.3f} عن الحقيقة", delta_color="inverse")
k2.metric("معامل x (مشبَّع)", f"{f1.b[1]:.3f}", delta=f"{f1.b[1] - 0.8:+.3f} عن الحقيقة", delta_color="inverse")
kinds = res.__dict__["_all_kinds"]
k3.metric("المؤشرات المكتشفة", ", ".join(f"{kinds[j]}{tau}" for j, tau in zip(res.selected, res.taus)) or "—")
st.plotly_chart(figs.result_figure(tt, y, res, None, "البيانات والتوفيق المشبَّع مع تواريخ الأحداث"))

st.markdown("## 🔗 التشبع في ARDL")
st.markdown(
    """
نموذج ARDL في صيغة تصحيح الخطأ يفصل بين **الأجل القصير** (الفروق) و**الأجل الطويل** (العلاقة التوازنية بين المستويات)، ويقيس
**سرعة التعديل** α: بأي سرعة يعود y إلى التوازن بعد صدمة. المؤشرات تضاف إليه هكذا:
"""
)
st.latex(r"\Delta y_t=c+\alpha\,(y_{t-1}-\theta' x_{t-1})+\sum_i \phi_i\Delta y_{t-i}+\sum_j \omega_j'\Delta x_{t-j}"
         r"+\underbrace{\sum_s \gamma_s d_s(t)}_{\text{مؤشرات غير مقيدة}}+\varepsilon_t")
st.markdown(
    """
- المؤشرات تدخل **غير مقيدة** (الحالة الثالثة في PSS): درجة بحجم γ تزيح التوازن طويل الأجل بمقدار γ/(−α).
- القيم الشاذة وتحولات المستوى غير المنمذجة **تحرف** سرعة التعديل α والمعاملات طويلة الأجل θ واختبار الحدود.
- قيم الحدود الحرجة لا تأخذ الاختيار في الحسبان: استخدم α صغيرًا وقدّم النتائج بالطريقتين.
"""
)
st.code("regress y x1 x2\nindsat, super tpval(0.01)        // يقرأ النموذج من الذاكرة + رسوم + مقارنة\n\n"
        "ardl c y D4p, lags(2 2 1)\nindsat, sis tpval(0.01)          // ARDL مشبّع + مقارنة طويلة الأجل + اختبار الحدود",
        language="stata")
with ui.box("example", "مثال حقيقي: دالة الاستهلاك البريطانية (DHSY)"):
    st.markdown("في نموذج ARDL(2,2,1) للاستهلاك البريطاني الربعي يكتشف التشبع تحولي مستوى في **1966q2** و**1972q1**. "
                "بعد نمذجتهما تغيّرت سرعة التعديل من **−1.37 إلى −1.54**، وانتقلت مرونة الدخل طويلة الأجل من 0.81 إلى 0.77، "
                "ورفض اختبار الحدود غياب العلاقة طويلة الأجل عند 1% (**F = 28.0**). ومع اختيار الفجوات آليًا تضاعفت سرعة التعديل "
                "من **−0.34 إلى −0.71**: تجاهل الكسور قد يخفي نصف سرعة العودة إلى التوازن.")
with ui.box("example", "مثال حقيقي: وفيات السائقين في بريطانيا"):
    st.markdown("انحدار لوغاريتم وفيات وإصابات السائقين على حركة المرور وسعر البنزين والأشهر. بعد التشبع (super) انخفضت مرونة "
                "الوفيات بالنسبة لسعر البنزين من **−0.54** إلى **−0.33**: الانحدار الأصلي كان ينسب إلى سعر البنزين جزءًا من "
                "تحولات المستوى، ومنها أثر قانون حزام الأمان (الذي يُؤرَّخ في الانحدار في 1983m7).")
ui.check("في ARDL، درجة حجمها γ = 0.4 وسرعة التعديل α = −0.5. بكم يزيح التوازن طويل الأجل؟", ["0.2", "0.8", "−0.4", "0.4"], 1,
         "الإزاحة = γ ÷ (−α) = 0.4 ÷ 0.5 = 0.8.", "rg_q1")
ui.check("ما الذي يبقى ثابتًا أثناء البحث حين تشبّع انحدارك؟", ["المؤشرات", "متغيراتك الاقتصادية", "لا شيء", "الثابت فقط"], 1,
         "التشبع يختار بين المؤشرات فقط ويحتفظ بمتغيرات نموذجك دائمًا.", "rg_q2")
ui.summary([
    "التشبع يحمي نموذجك: متغيراتك ثابتة، والمؤشرات وحدها تُختار.",
    "بعد regress أو ardl يكفي أمر واحد: indsat, super tpval(0.01).",
    "الأحداث غير المنمذجة تحرف المعاملات وسرعة التعديل واختبار الحدود.",
    "قدّم النتائج مع التشبع ودونه، واستخدم α صغيرًا لأن قيم الحدود لا تأخذ الاختيار في الحسبان.",
])
