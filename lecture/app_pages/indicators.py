import streamlit as st

from lib import figs, ui

ui.hero("الدرس 5", "المؤشرات الوهمية: حجر البناء", "Indicator (dummy) variables — the building blocks",
        "قبل أن نضع مئة مؤشر في النموذج، يجب أن نفهم المؤشر الواحد فهمًا عميقًا: ما شكله، وماذا يقيس معامله، "
        "وكيف تُبنى منه كل الأنواع الأخرى.", "green")
ui.objectives([
    "تعريف المؤشر وكيف يقرأ معامله",
    "الأشكال الثلاثة الأساسية: النبضة والدرجة والاتجاه المنكسر",
    "العلاقة الذهبية التي تربط الأشكال ببعضها",
    "مصفوفة التشبع: لماذا لا يمكن تقديرها مباشرة",
], minutes=15)

st.markdown("## 🧱 ما المؤشر؟")
st.markdown(
    f"""
{ui.t('المؤشر', 'indicator / dummy variable')} متغير **نصنعه نحن**، لا نجمعه من الإحصاءات. قيمه أصفار في معظم الفترات،
وقيمة غير صفرية (عادة 1) في فترات محددة. حين نضيفه إلى الانحدار:
"""
)
st.latex(r"y_t = \beta' x_t + \gamma_j\, d_j(t) + \varepsilon_t")
st.markdown(
    """
يصبح معامله $\\gamma_j$ هو **حجم الحدث** الذي يلتقطه، وإحصاءة $t$ الخاصة به تقول هل هذا الحدث **معنوي** أم أنه
مجرد ضجيج عادي. الفكرة كلها: **المؤشر سؤال نطرحه على البيانات** — «هل حدث شيء استثنائي في هذا التاريخ؟» —
والمعامل هو الجواب.
"""
)
with ui.box("analogy", "مفتاح الضوء"):
    st.markdown("تخيّل المؤشر مفتاح ضوء: مطفأ (0) في كل الفترات، ومضاء (1) في الفترات التي نريد فحصها. "
                "المعامل يقيس **كم يتغير** y حين نضيء المفتاح. إن لم يتغير شيء يُذكر، فالمفتاح لا لزوم له.")

st.markdown("## 🔺 الأشكال الثلاثة الأساسية")
st.markdown("كل الأنواع التي ستدرسها مبنية على ثلاثة أشكال. لكل شكل حدث يناسبه:")
c1, c2, c3 = st.columns(3)
with c1:
    with ui.box("def", "النبضة (impulse)"):
        st.latex(r"I_j(t)=\mathbf 1(t=j)")
        st.markdown("تساوي 1 في الفترة j **فقط**. تلتقط **قيمة شاذة**: حدثًا أثّر فترة واحدة ثم زال. "
                    "معاملها = الفرق بين قيمة تلك الفترة وما كان متوقعًا.")
with c2:
    with ui.box("def", "الدرجة (step)"):
        st.latex(r"S_j(t)=\mathbf 1(t\ge j)")
        st.markdown("تساوي 1 من الفترة j **إلى النهاية**. تلتقط **تحول المستوى**: حدثًا غيّر المتوسط تغييرًا دائمًا. "
                    "معاملها = الفرق بين المتوسط بعد j وقبله.")
with c3:
    with ui.box("def", "الاتجاه المنكسر (broken trend)"):
        st.latex(r"T_j(t)=(t-j+1)\,\mathbf 1(t\ge j)")
        st.markdown("صفر قبل j، ثم يزداد 1، 2، 3... تلتقط **تغيّر الميل**: حدثًا غيّر معدل النمو. "
                    "معاملها = التغير في الميل لكل فترة.")

with ui.box("why", "العلاقة الذهبية"):
    st.markdown(
        """
**الدرجة = مجموع نبضات متتالية**، و**الاتجاه المنكسر = مجموع درجات متتالية**. لذلك يمكن لعدد كبير من النبضات أن
«يقلّد» تحول مستوى، لكن ذلك يكلف مؤشرات كثيرة يصعب على الاختبار اكتشافها كلها. أما **الشكل المطابق** فيلتقط الحدث
بمؤشر **واحد** ومعامل واحد، فيكون أقوى بكثير. هذا هو السبب في وجود أنواع متعددة من التشبع: كل نوع يطابق شكلًا من الأحداث.
"""
    )
with ui.box("example", "قراءة معامل بالأرقام"):
    st.markdown(
        """
في نموذج التدفق السنوي لنهر النيل (بوحدة 100 مليون م³) مع التشبع الفائق (نبضات ودرجات، α = 1%) تُكتشف درجة في **1899**
معاملها نحو **−281**. المعنى: ابتداء من 1899 أصبح متوسط التدفق أقل بنحو 281 وحدة مما كان قبلها (وهو تاريخ بناء سد أسوان
القديم). وفي النموذج نفسه نبضة في **1913** معاملها نحو **−315**: تدفق تلك السنة وحدها (456) كان أقل بنحو 315 مما يتوقعه
مستوى نظامها.
"""
    )

st.markdown("## ▶️ شاهد المؤشر يتحرك عبر الزمن")
st.markdown("اختر النوع ثم اضغط ▶. كل إطار يعرض المؤشر نفسه لكنه يبدأ في تاريخ مختلف. "
            "**التشبع** يعني أن نضع كل هذه الأعمدة في النموذج دفعة واحدة، عمودًا لكل تاريخ.")
kind = st.segmented_control("نوع المؤشر", ["IIS", "SIS", "TIS", "QIS", "DIS", "PIS", "BIS", "MIS"],
                            default="IIS", key="ind_kind")
names = {"IIS": "نبضة", "SIS": "درجة", "TIS": "اتجاه منكسر", "QIS": "اتجاه تربيعي منكسر", "DIS": "نبضة مفرَّقة",
         "PIS": "نبضة زوجية", "BIS": "دالة مصمَّمة (بركانية)", "MIS": "درجة مضروبة في متغير x"}
st.caption(f"النوع المعروض: **{names[kind or 'IIS']}**")
st.plotly_chart(figs.indicator_sweep(kind or "IIS"), key=f"sweep_{kind}")

st.markdown("## 🔲 مصفوفة التشبع")
st.markdown(
    """
حين نجمع **كل** المؤشرات من نوع واحد، مؤشرًا لكل تاريخ، نحصل على مصفوفة مربعة تقريبًا. لـ IIS هي مصفوفة الوحدة
(قطرها آحاد)، ولـ SIS مثلث سفلي من الآحاد:
"""
)
st.latex(r"D_{IIS}=I_T=\begin{pmatrix}1&0&\cdots&0\\0&1&\cdots&0\\\vdots&&\ddots&\vdots\\0&0&\cdots&1\end{pmatrix},\qquad"
         r"D_{SIS}=\begin{pmatrix}1&0&\cdots&0\\1&1&\cdots&0\\\vdots&&\ddots&\vdots\\1&1&\cdots&1\end{pmatrix}")
st.markdown(
    """
النموذج المشبَّع $y = X\\beta + D\\gamma + \\varepsilon$ فيه $k + T$ معلمة، أي أكثر من عدد المشاهدات $T$. المربعات
الصغرى **لا تستطيع** تقديره مباشرة: كأنك تحاول حل معادلات عددها أقل من عدد المجاهيل. الحل الذكي هو موضوع الدرس التالي.
"""
)
with ui.box("warn", "اختلاف الصيغ بين البرامج"):
    st.markdown("صيغة الدرجة تختلف بين البرمجيات: حزمة gets في R ومكتبة indsat تستخدمان 1(t ≥ j)، أما Autometrics "
                "وCastle وزملاؤه (2015) فيستخدمون 1(t ≤ j). المعنى الاقتصادي واحد، لكن **إشارة المعامل تنقلب**. "
                "انتبه لهذا حين تقارن نتائجك بورقة منشورة.")

ui.check("درجة تبدأ في 2009 معاملها +3.2. ماذا يعني ذلك؟",
         ["القيمة في 2009 وحدها أعلى بـ 3.2", "المتوسط من 2009 فصاعدًا أعلى بـ 3.2 من قبلها",
          "الميل زاد بـ 3.2 كل سنة", "لا معنى له"], 1, "الدرجة تلتقط تحولًا دائمًا في المستوى ابتداء من تاريخها.", "ind_q1")
ui.check("لماذا نفضّل SIS على IIS لالتقاط تحول مستوى؟",
         ["لأن SIS أسرع", "لأن الدرجة تلتقط التحول بمؤشر واحد بدل سلسلة نبضات", "لأن IIS لا يعمل مع السلاسل الزمنية",
          "لا فرق"], 1, "الشكل المطابق يحتاج معاملًا واحدًا، فتكون قوة اكتشافه أعلى بكثير.", "ind_q2")
ui.summary([
    "المؤشر سؤال نطرحه على البيانات: هل حدث شيء في هذا التاريخ؟ ومعامله هو الجواب.",
    "النبضة للقيم الشاذة، والدرجة لتحولات المستوى، والاتجاه المنكسر لتغيّر الميل.",
    "الدرجة مجموع نبضات، والاتجاه مجموع درجات؛ والشكل المطابق أقوى دائمًا.",
    "مصفوفة التشبع فيها معالم أكثر من المشاهدات، فلا تُقدَّر بـ OLS مباشرة.",
])
ui.nav_hint("فكرة التشبع والانقسام")
