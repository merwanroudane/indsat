    "البواقي تكشف ما لم يفسره النموذج، لكن القيم الشاذة قد تخفي نفسها.",
    "إحصاءة t = المعامل ÷ الخطأ المعياري؛ والقيمة الاحتمالية تقيس دور الصدفة.",
    "مع اختبارات كثيرة نتوقع α × عددها نتائج زائفة: لذا نستخدم α صغيرًا في التشبع.",
    "المتغير الوهمي هو حجر البناء: التشبع يضع واحدًا لكل تاريخ ويترك الاختبار يختار.",
